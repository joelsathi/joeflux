// Writes website/docs/reference/tools.md and themes.md from the live tool and theme registries.
import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import { createProjectTools } from '../packages/tools/src/index.js';
import { THEME_OPTIONS, resolveTheme } from '../packages/presets/src/themes.js';

const GROUPS = [
  ['Project and scenes', /^(project_|scene_|catalog|validate|style_set|asset_import|artwork_import)/],
  ['Brief and director', /^(brief_|knowledge_|review_|skill_)/],
  ['Brand kits and backgrounds', /^(brand_|background_)/],
  ['Templates, components and plugins', /^(template_|component_|plugin_|animation_plugin)/],
  ['Camera and screen', /^(camera_|screen_)/],
  ['Source timing', /^(source_|playback_)/],
  ['Rendering and review', /^(render_|quality_|variation_|transition_|film_|assemble|review_contact|history_)/],
];
const cell = (text) => String(text).replaceAll('|', '\\|').replaceAll('\n', ' ').replaceAll('{', '\\{').replaceAll('}', '\\}').replaceAll('<', '&lt;');
const tools = createProjectTools(path.resolve('projects/demo')).list();
const used = new Set();
let page = `---\ntitle: Tools\ndescription: Every project tool available to the Studio, the CLI and MCP clients.\n---\n\n# Tools\n\nThe Studio, \`pnpm tool\` and MCP clients call the same ${tools.length} tools. Mutating tools validate the result, write nothing when it is invalid, and record one undo step. This page is generated by \`node scripts/generate-docs-reference.mjs\`.\n`;
for (const [title, pattern] of [...GROUPS, ['Other', /./]]) {
  const group = tools.filter((tool) => !used.has(tool.name) && pattern.test(tool.name));
  if (!group.length) continue;
  group.forEach((tool) => used.add(tool.name));
  page += `\n## ${title}\n\n| Tool | Changes the project | Description |\n| --- | --- | --- |\n${group.map((tool) => `| \`${tool.name}\` | ${tool.mutates ? 'Yes' : 'No'} | ${cell(tool.description)} |`).join('\n')}\n`;
}
await writeFile('website/docs/reference/tools.md', page);

const swatch = (color) => `<span style={{display:'inline-block',width:14,height:14,borderRadius:4,background:'${color}',border:'1px solid rgba(127,127,127,.4)',verticalAlign:'middle'}} /> \`${color}\``;
const rows = THEME_OPTIONS.map(({ id, label }) => { const theme = resolveTheme(id); return `| \`${id}\` | ${cell(label)} | ${theme.mode ?? (id === 'navy-dark' ? 'dark' : 'light')} | ${swatch(theme.background)} | ${swatch(theme.text)} | ${swatch(theme.accent)} |`; });
await writeFile('website/docs/reference/themes.mdx', `---\ntitle: Themes\ndescription: Built-in, Oxygen and brand kit themes with their main colors.\n---\n\n# Themes\n\nSet \`theme\` on the project or on a scene. Brand kit themes are named \`<kit>-<theme>\`, and backgrounds add a paired \`background-<kit>-<background>\` theme. This page is generated by \`node scripts/generate-docs-reference.mjs\` from the installed kits.\n\n| Id | Label | Mode | Background | Text | Accent |\n| --- | --- | --- | --- | --- | --- |\n${rows.join('\n')}\n`);
console.log(`${tools.length} tools, ${THEME_OPTIONS.length} themes`);
