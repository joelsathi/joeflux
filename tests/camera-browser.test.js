import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp,mkdir,writeFile,readFile} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import path from 'node:path';
import {chromium} from '@playwright/test';
import {startPreview} from '../packages/preview-server/src/index.js';
import {createRenderServer} from '../packages/renderer/src/server.js';
import {browserLaunchOptions} from '../packages/renderer/src/index.js';

test('camera preset controls save, preserve playback, and agree with export after backward scrubbing',async()=>{
 const root=await mkdtemp(path.join(tmpdir(),'camera motion '));await mkdir(path.join(root,'scenes'));await mkdir(path.join(root,'assets'));
 await writeFile(path.join(root,'assets/screen.svg'),'<svg xmlns="http://www.w3.org/2000/svg" width="1920" height="1200"><rect width="1920" height="1200" fill="#f5f8fc"/><rect x="960" width="960" height="540" fill="#336688"/><circle cx="400" cy="800" r="120" fill="#ee7330"/></svg>');
 const scene={id:'camera',preset:'recorded-showcase',durationFrames:144,params:{asset:'screen'},camera:{end:{rotateY:12}},playback:{startSeconds:2,segments:[{outputStart:0,outputEnd:144,rate:1.2}]}};
 const file=path.join(root,'scenes/camera.json');await writeFile(file,JSON.stringify(scene));await writeFile(path.join(root,'project.json'),JSON.stringify({version:1,name:'Camera',output:{width:640,height:360,fps:24,audio:false},assets:{screen:'assets/screen.svg'},scenes:[{id:'camera',file:'scenes/camera.json'}]}));
 const preview=await startPreview(root,0,{app:'classic'}),server=await createRenderServer(root),browser=await chromium.launch(browserLaunchOptions());
 try{
  const page=await browser.newPage({viewport:{width:1600,height:1000}});page.setDefaultTimeout(5000);await page.goto(preview.url);await page.waitForSelector('canvas[data-rendered-scene]');
  await page.getByLabel('Camera motion',{exact:true}).selectOption('detail-pan');
  await page.getByLabel('Pan destination X',{exact:true}).fill('0.85');
  await page.getByRole('button',{name:'Compose shot',exact:true}).click();
  assert.ok((await page.locator('.workspace').getAttribute('class')).includes('is-composing'));
  await page.locator('.composition-motion-view canvas[data-rendered-scene="camera"]').waitFor();
  assert.equal(await page.getByLabel('Framing preview',{exact:true}).isVisible(),false);
  await page.getByLabel('Screen size',{exact:true}).fill('1.15');
  await page.getByLabel('Rotation X',{exact:true}).click();
  await page.getByLabel('Rotate X',{exact:true}).fill('18');
  await page.getByLabel('Rotation X',{exact:true}).click();
  await page.getByText('Backdrop',{exact:true}).click();
  await page.getByRole('button',{name:'Slate',exact:true}).click();
  await page.getByRole('button',{name:'Select area',exact:true}).click();
  assert.equal(await page.getByLabel('Framing preview',{exact:true}).isVisible(),true);
  const source=page.getByLabel('Composition area',{exact:true});
  await page.waitForSelector('.composition-source[data-ready="true"]');
  const box=await source.boundingBox();
  assert.ok(box.width>900,'Studio stage should use the available width.');
  await page.getByRole('button',{name:'To position',exact:true}).click();
  assert.equal(await page.getByLabel('Camera timeline',{exact:true}).inputValue(),'114');
  await page.getByRole('button',{name:'From position',exact:true}).click();
  assert.equal(await page.getByLabel('Camera timeline',{exact:true}).inputValue(),'29');
  const drag=async(x1,y1,x2,y2)=>{await page.mouse.move(box.x+box.width*x1,box.y+box.height*y1);await page.mouse.down();await page.mouse.move(box.x+box.width*x2,box.y+box.height*y2,{steps:8});await page.mouse.up();};
  await page.getByRole('button',{name:'Draw area',exact:true}).click();
  await drag(.1,.2,.5,.6);
  assert.ok(Math.abs(Number(await page.getByLabel('Studio zoom',{exact:true}).inputValue())-2.5)<.02);
  await page.getByRole('button',{name:'To',exact:true}).click();
  await page.getByRole('button',{name:'Draw area',exact:true}).click();
  await drag(.55,.35,.95,.75);
  await page.getByLabel('Framing preview',{exact:true}).waitFor();
  await page.getByRole('button',{name:'Preview motion',exact:true}).click();
  await page.getByRole('button',{name:'Pause',exact:true}).click();
  assert.equal(await page.locator('.camera-composer').isVisible(),true);
  await page.locator('.composition-motion-view canvas[data-rendered-scene="camera"]').waitFor();
  await page.getByRole('button',{name:'Edit framing',exact:true}).click();
  const [saved]=await Promise.all([page.waitForResponse(r=>r.request().method()==='PUT'),page.getByRole('button',{name:'Save',exact:true}).click()]);assert.equal(saved.status(),200,await saved.text());
  const data=JSON.parse(await readFile(file,'utf8'));assert.equal(data.camera,undefined);assert.equal(data.cameraMotion.preset,'detail-pan');assert.ok(Math.abs(data.cameraMotion.endFocusX-.75)<.01);assert.ok(Math.abs(data.cameraMotion.focusX-.3)<.01);assert.ok(Math.abs(data.cameraMotion.scale-2.5)<.02);assert.deepEqual(data.playback,scene.playback);assert.equal(data.cameraMotion.presentation,'studio');assert.equal(data.cameraMotion.stageScale,1.15);assert.equal(data.cameraMotion.rotateX,18);assert.equal(data.cameraMotion.backdrop,'slate');
  await page.reload();await page.waitForSelector('canvas[data-rendered-scene]');await page.addStyleTag({content:'.canvas-wrap{width:640px!important;height:360px!important;border-radius:0!important}'});
  const exp=await browser.newPage({viewport:{width:640,height:360}});await exp.goto(server.origin);await exp.waitForFunction(()=>window.joeFluxReady);
  for(const frame of [12,96,45,143]){
   await exp.evaluate(frame=>window.renderScene({sceneId:'camera',frame}),frame);
   await page.locator('.transport input').evaluate((node,value)=>{Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(node,String(value));node.dispatchEvent(new Event('input',{bubbles:true}));node.dispatchEvent(new Event('change',{bubbles:true}));},frame);
   await page.waitForFunction(frame=>document.querySelector('canvas').dataset.renderedFrame===String(frame),frame);
   assert.equal(await page.locator('.canvas-wrap canvas[data-asset]').evaluate(canvas=>canvas.toDataURL()),await exp.locator('#stage canvas[data-asset]').evaluate(canvas=>canvas.toDataURL()),'The source pixels must match the exported frame.');
   assert.equal(await page.locator('.canvas-wrap canvas[data-asset]').evaluate(canvas=>canvas.style.transform),await exp.locator('#stage canvas[data-asset]').evaluate(canvas=>canvas.style.transform),'The camera pose must match export.');
  }
  await page.getByRole('button',{name:'Compose shot',exact:true}).click();
  await page.getByRole('button',{name:'Select area',exact:true}).click();
  await page.waitForSelector('.composition-source[data-ready="true"]');
  await page.getByRole('group',{name:'From framing',exact:true}).focus();
  await page.keyboard.press('ArrowRight');
  assert.ok(Number(await page.locator('.camera-composer .composition-focus-x').textContent())>data.cameraMotion.focusX+.005);
  const again=await page.getByLabel('Composition area',{exact:true}).boundingBox();
  await page.mouse.click(again.x+again.width*.75,again.y+again.height*.8);
  assert.ok(Number(await page.locator('.camera-composer .composition-focus-x').textContent())>.7,'Clicking an unselected point should move the camera focus without changing zoom.');
  assert.ok(Math.abs(Number(await page.getByLabel('Studio zoom',{exact:true}).inputValue())-data.cameraMotion.scale)<.02);
  await page.getByRole('button',{name:'Resize nw',exact:true}).focus();
  await page.keyboard.press('Shift+ArrowLeft');
  assert.ok(Number(await page.getByLabel('Studio zoom',{exact:true}).inputValue())<data.cameraMotion.scale);
  await page.getByRole('button',{name:'Revert',exact:true}).click();
  await page.waitForFunction(()=>!document.querySelector('.camera-composer'));
  assert.ok(Math.abs(Number(await page.getByLabel('Camera zoom',{exact:true}).inputValue())-data.cameraMotion.scale)<.03);
  assert.deepEqual(JSON.parse(await readFile(file,'utf8')),data);
 }finally{await browser.close();await preview.close();await server.close();}
});
