import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, mkdir, readFile, writeFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { evaluateSourceTime, mapSourceFrame } from '../packages/motion/src/timing.js';

const moments = [{ type: 'play', startSeconds: 1, endSeconds: 2 }, { type: 'play', startSeconds: 5, endSeconds: 6, rate: 2 }, { type: 'hold', sourceSeconds: 6, frames: 24 }];
test('source moments skip waiting and hold a result at fractional and backward seeks', () => {
  const playback = { sourceFps: 30, moments };
  assert.equal(evaluateSourceTime(playback, 0, 24), 1);
  assert.equal(evaluateSourceTime(playback, 23.5, 24), 1 + 23.5 / 24);
  assert.equal(evaluateSourceTime(playback, 24, 24), 5);
  assert.equal(evaluateSourceTime(playback, 30, 24), 5.5);
  assert.equal(evaluateSourceTime(playback, 36, 24), 6);
  assert.equal(evaluateSourceTime(playback, 59, 24), 6);
  assert.equal(evaluateSourceTime(playback, 12, 24), 1.5);
  assert.equal(mapSourceFrame(playback, 30, 24), 165);
});
test('moment compilation validates monotonic ranges, finite values, frame totals and conflicting legacy timing', async () => {
  const { compileSourceMoments, sourceMomentErrors } = await import('../packages/motion/src/source-moments.js');
  assert.equal(compileSourceMoments(moments, 24).totalFrames, 60);
  assert.deepEqual(sourceMomentErrors({ moments }, { fps: 24, durationFrames: 60 }), []);
  assert.match(sourceMomentErrors({ moments }, { fps: 24, durationFrames: 59 }).join(' '), /duration/);
  assert.match(sourceMomentErrors({ moments: [{ type: 'play', startSeconds: 4, endSeconds: 5 }, { type: 'hold', sourceSeconds: 2, frames: 3 }] }, { fps: 24 }).join(' '), /order/);
  for (const bad of [[], [{ type: 'hold', sourceSeconds: NaN, frames: 2 }], [{ type: 'play', startSeconds: 0, endSeconds: 1, rate: 0 }], [{ type: 'play', startSeconds: 0, endSeconds: .001 }]]) assert.throws(() => compileSourceMoments(bad, 24));
  assert.throws(() => compileSourceMoments([{ type: 'hold', sourceSeconds: 1, frames: 2, rate: 2 }], 24), /field/);
  assert.throws(() => evaluateSourceTime({ moments }, NaN, 24), /finite/);
  assert.match(sourceMomentErrors({ moments, segments: [{ outputStart: 0, outputEnd: 2, rate: 2 }] }, { fps: 24 }).join(' '), /combine/);
});
test('source tools preserve authored camera choices and undo trim, skip and result hold', async (t) => {
  const { PLAYBACK_TOOLS } = await import('../packages/tools/src/playback-tools.js');
  const { createToolRunner } = await import('../packages/tools/src/runner.js');
  const root = await mkdtemp(path.join(tmpdir(), 'source-moments-'));
  t.after(() => rm(root, { recursive: true, force: true }));
  await mkdir(path.join(root, 'scenes'));
  await mkdir(path.join(root, 'assets'));
  await promisify(execFile)('ffmpeg', ['-v', 'error', '-f', 'lavfi', '-i', 'color=c=blue:s=32x18:d=10:r=30', '-an', path.join(root, 'assets/clip.mp4')]);
  const scene = { id: 'screen', kind: 'screen', durationFrames: 240, screen: { asset: 'clip' }, camera: { shots: [{ at: 0 }, { at: .4, zoom: 2, focus: [.7, .3] }, { at: 1 }] } };
  const original = JSON.stringify(scene);
  await writeFile(path.join(root, 'scenes/screen.json'), original);
  await writeFile(path.join(root, 'project.json'), JSON.stringify({ version: 1, output: { width: 320, height: 180, fps: 24, audio: false }, assets: { clip: 'assets/clip.mp4' }, scenes: [{ id: 'screen', file: 'scenes/screen.json' }] }));
  const runner = createToolRunner(root, PLAYBACK_TOOLS);
  const info = await runner.call('source_timeline', { id: 'screen' });
  assert.equal(info.sourceFps, 30); assert.equal(info.timestamps.length, 300);
  await assert.rejects(runner.call('source_trim', { id: 'screen', startSeconds: 0, endSeconds: 11 }), /source duration/);
  await runner.call('source_trim', { id: 'screen', startSeconds: 1, endSeconds: 9 });
  await runner.call('source_skip_wait', { id: 'screen', startSeconds: 3, endSeconds: 5 });
  await runner.call('source_hold_result', { id: 'screen', sourceSeconds: 9, frames: 24 });
  const saved = JSON.parse(await readFile(path.join(root, 'scenes/screen.json'), 'utf8'));
  assert.deepEqual(saved.camera, scene.camera);
  assert.equal(saved.durationFrames, 168);
  assert.equal(evaluateSourceTime(saved.playback, 48, 24), 5);
  assert.equal(evaluateSourceTime(saved.playback, 150, 24), 9);
  await runner.call('source_trim', { id: 'screen', startSeconds: 0, endSeconds: 10 });
  const expanded = JSON.parse(await readFile(path.join(root, 'scenes/screen.json'), 'utf8'));
  assert.equal(expanded.durationFrames, 216);
  assert.ok(expanded.playback.moments.some(item => item.type === 'hold' && item.sourceSeconds === 9));
  await runner.undo();
  for (let i = 0; i < 3; i++) await runner.undo();
  assert.equal(await readFile(path.join(root, 'scenes/screen.json'), 'utf8'), original);
  const legacy = { ...scene, playback: { segments: [{ outputStart: 0, outputEnd: 240, rate: 2 }], holds: [] } };
  await writeFile(path.join(root, 'scenes/screen.json'), JSON.stringify(legacy));
  await assert.rejects(runner.call('source_trim', { id: 'screen', startSeconds: 0, endSeconds: 2 }), /legacy/);
  await runner.call('source_set_moments', { id: 'screen', moments: [{ type: 'play', startSeconds: 0, endSeconds: 2 }] });
  assert.deepEqual(JSON.parse(await readFile(path.join(root, 'scenes/screen.json'), 'utf8')).camera, scene.camera);
  await runner.undo();
  assert.deepEqual(JSON.parse(await readFile(path.join(root, 'scenes/screen.json'), 'utf8')), legacy);
  const captioned = { ...scene, caption: { text: 'This result needs enough time to read the complete explanation clearly' } };
  await writeFile(path.join(root, 'scenes/screen.json'), JSON.stringify(captioned));
  await assert.rejects(runner.call('source_trim', { id: 'screen', startSeconds: 0, endSeconds: 1 }), error => error.issues?.some(issue => issue.includes('reading hold')));
  assert.deepEqual(JSON.parse(await readFile(path.join(root, 'scenes/screen.json'), 'utf8')), captioned);
});
test('source tool rejects shortening that loses camera keyframes, and does not overwrite legacy timing implicitly', async () => {
  const { sourceMomentsForScene, applySourceMoments } = await import('../packages/tools/src/playback-tools.js');
  assert.throws(() => sourceMomentsForScene({ durationFrames: 48, playback: { segments: [{ outputStart: 0, outputEnd: 48, rate: 2 }] } }, 24), /legacy/);
  const scene = { durationFrames: 48, camera: { keyframes: [{ frame: 0, scale: 1 }, { frame: 40, scale: 2 }] } };
  assert.throws(() => applySourceMoments(scene, [{ type: 'play', startSeconds: 0, endSeconds: .5 }], 24), /camera/);
  assert.equal(scene.durationFrames, 48);
});

test('derived source edits drop pieces shorter than one output frame', async (t) => {
  const { PLAYBACK_TOOLS } = await import('../packages/tools/src/playback-tools.js');
  const { createToolRunner } = await import('../packages/tools/src/runner.js');
  const root = await mkdtemp(path.join(tmpdir(), 'source-slivers-'));
  t.after(() => rm(root, { recursive: true, force: true }));
  await mkdir(path.join(root, 'scenes')); await mkdir(path.join(root, 'assets'));
  await promisify(execFile)('ffmpeg', ['-v', 'error', '-f', 'lavfi', '-i', 'color=c=blue:s=32x18:d=4:r=60', '-an', path.join(root, 'assets/clip.mp4')]);
  await writeFile(path.join(root, 'scenes/screen.json'), JSON.stringify({ id: 'screen', kind: 'screen', durationFrames: 72, screen: { asset: 'clip' }, camera: { shots: [{ at: 0 }, { at: 1 }] } }));
  await writeFile(path.join(root, 'project.json'), JSON.stringify({ version: 1, output: { width: 320, height: 180, fps: 24, audio: false }, assets: { clip: 'assets/clip.mp4' }, scenes: [{ id: 'screen', file: 'scenes/screen.json' }] }));
  const runner = createToolRunner(root, PLAYBACK_TOOLS);
  await runner.call('source_trim', { id: 'screen', startSeconds: 0, endSeconds: 3 });
  await runner.call('source_skip_wait', { id: 'screen', startSeconds: 1 / 60, endSeconds: 1 });
  const saved = JSON.parse(await readFile(path.join(root, 'scenes/screen.json'), 'utf8'));
  assert.deepEqual(saved.playback.moments, [{ type: 'play', startSeconds: 1, endSeconds: 3 }]);
  assert.equal(saved.durationFrames, 48);
});
